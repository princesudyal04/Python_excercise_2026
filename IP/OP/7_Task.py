# Input :
# Convert Decimal number to octal using print() output formatting
# num = 8

# Expected Output :
# The octal number of decimal number 8 is 10

num = 8
print(f"The octal number of decimal {num} is {num:o}")    #octal
print(f"The octal number of decimal {num} is {num:b}")    #binary
print(f"The octal number of decimal {num} is {num:d}")    #decimal